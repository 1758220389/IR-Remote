"""Generate only this UI's 16x16 glyphs from an installed Windows font.

Source: Microsoft Windows SimSun, C:/Windows/Fonts/simsun.ttc, face 0.
No third-party bitmap downloads; original font is not copied into the repo.
The installed font remains subject to its Microsoft/Founder's font license;
this generator is not a grant of font redistribution rights.
Requires Pillow (tested version and input SHA-256 recorded in generated C).
Run: python tools/generate_ui_font.py [--font PATH] [--output PATH]
Packing is identical to OLED_ShowImage: x-first columns, 8 vertical bits/byte,
top page then bottom page, least significant bit at top. No font needed on MCU.
"""
import argparse
import hashlib
from pathlib import Path
import PIL
from PIL import Image, ImageDraw, ImageFont

# Union of labels/instructions in pic/OLED页面.png plus concise split-row labels.
TEXT = "配置学习接收中已单击任意按键完成绑定长确认切换继续退出保存至取消成功上下选择设置正常使用页标题闪烁信号短请遥控器等待返回其余"


def generate(font_path):
    font = ImageFont.truetype(str(font_path), 16, index=0)
    lines = ["/* Generated by tools/generate_ui_font.py; do not hand-edit.",
             f" * Font: {font_path.name}, face 0, size 16; Pillow {PIL.__version__}.",
             f" * Font SHA256: {hashlib.sha256(font_path.read_bytes()).hexdigest()}",
             " * Source/license details: generator module docstring. */",
             '#include "ui_font.h"', "#include <stddef.h>",
             "typedef struct { uint16_t codepoint; uint8_t bitmap[32]; } UiGlyph;",
             "static const UiGlyph glyphs[] = {"]
    for char in sorted(set(TEXT), key=ord):
        image = Image.new("1", (16, 16))
        draw = ImageDraw.Draw(image)
        left, top, right, bottom = draw.textbbox((0, 0), char, font=font)
        assert right-left <= 16 and bottom-top <= 16, char
        draw.text(((16-(right-left))//2-left, (16-(bottom-top))//2-top),
                  char, font=font, fill=1)
        data = [sum((1 << bit) if image.getpixel((x, page*8+bit)) else 0
                    for bit in range(8)) for page in range(2) for x in range(16)]
        assert any(data), char
        lines.append("    {0x%04Xu, {%s}}, /* %s */" %
                     (ord(char), ", ".join("0x%02X" % b for b in data), char))
    lines += ["};", "const uint8_t *UiFont_Find(uint32_t codepoint)", "{",
              "    unsigned i;",
              "    for (i = 0; i < sizeof glyphs / sizeof glyphs[0]; ++i)",
              "        if (glyphs[i].codepoint == codepoint) return glyphs[i].bitmap;",
              "    return NULL;", "}", ""]
    return "\n".join(lines)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--font", type=Path, default=Path("C:/Windows/Fonts/simsun.ttc"))
    parser.add_argument("--output", type=Path,
                        default=Path(__file__).resolve().parents[1]/"code/Main/ui_font.c")
    args = parser.parse_args()
    args.output.write_text(generate(args.font), encoding="utf-8", newline="\n")
    print(f"Generated {len(set(TEXT))} glyphs: {args.output}")


if __name__ == "__main__":
    main()
