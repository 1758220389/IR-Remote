"""Verify the approved PC artifacts and regenerate the fixed MCU constants."""
import argparse
from pathlib import Path
import json
from hashlib import sha256

import joblib
import numpy as np
import pandas as pd

ML = Path(__file__).resolve().parents[1]


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    folder = ML / "models/v1"
    model_file = folder / "recommended_C.joblib"
    manifest = ML / "data/v1/manifest.csv"
    run = json.loads((folder / "run.json").read_text())
    assert sha256(manifest.read_bytes()).hexdigest() == run["manifest_sha256"]
    data = pd.read_csv(manifest)
    main = data[data.included & data.scope.eq("complete_guided")]
    assert main.groupby("session").size().tolist() == [30] * 4
    assert main.label.value_counts().to_dict() == {"CW": 40, "CCW": 40, "NONE": 40}
    assert (data.included & data.scope.eq("supplemental_manual")).sum() == 10
    # The local joblib was produced by the approved PC training run.
    artifact = joblib.load(model_file)
    details = json.loads((folder / "recommended_C.json").read_text())
    assert json.loads(json.dumps(artifact["details"])) == details and details["training_sessions"] == sorted(main.session.unique())
    scaler, lr = artifact["model"][0], artifact["model"][1]
    assert int(scaler.n_samples_seen_) == 120
    assert details["classes"] == lr.classes_.tolist() == ["CCW", "CW", "NONE"]
    assert details["features"] == ["gyro_integral_z_deg"]
    w = lr.coef_ / scaler.scale_
    b = lr.intercept_ - w @ scaler.mean_
    np.testing.assert_allclose(w, details["weights"], rtol=0, atol=1e-14)
    np.testing.assert_allclose(b, details["intercept"], rtol=0, atol=1e-14)
    still = [pd.read_csv(ML / row.raw_csv)[["gx_raw","gy_raw","gz_raw"]].to_numpy() / 131
             for row in main[main.stationary & main.label.eq("NONE")].itertuples()]
    np.testing.assert_allclose(np.concatenate(still).mean(axis=0), details["bias_dps"], rtol=0, atol=1e-12)
    def c(value):
        return f"{float(value):.17e}f"
    digest = sha256((folder / "recommended_C.json").read_bytes()).hexdigest()
    header = ("/* Generated by export_recognizer.py. PC parameters SHA-256: " + digest + " */\n"
              "#ifndef GESTURE_MODEL_V1_H\n#define GESTURE_MODEL_V1_H\n"
              "#define GESTURE_MODEL_VERSION 0x00010000u\n"
              "#define GESTURE_Z_BIAS_DPS " + c(details["bias_dps"][2]) + "\n"
              "static const float gesture_weights[3] = {" + ", ".join(map(c, w[:, 0])) + "};\n"
              "static const float gesture_intercepts[3] = {" + ", ".join(map(c, b)) + "};\n#endif\n")
    path = ML / "firmware/gesture_model_v1.h"
    if args.check:
        assert path.read_text(encoding="ascii") == header
    else:
        path.write_text(header, encoding="ascii")
    print(f"Verified 120 fitted windows, 10 supplemental only, PC parameter SHA-256 {digest}")


if __name__ == "__main__":
    main()

